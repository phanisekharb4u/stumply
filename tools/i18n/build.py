"""Builds js/i18n-data.js (translations + help guide) from the files in this folder.

Run from anywhere:  python3 tools/i18n/build.py

d1.py … d7.py  English text → [Telugu, Hindi, Tamil, Kannada, Malayalam]
               Keys starting with % are templates used by I18N_PAT in js/lang.js.
help.py        The Help guide (English and Telugu).
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
src = lambda name: open(os.path.join(HERE, name), encoding='utf-8').read()

D = {}
for f in ['d1', 'd2', 'd3', 'd4']:
    g = {'N': None}; exec(src(f + '.py'), g)
    for k, v in g.items():
        if re.fullmatch(r'D\d', k): D.update(v)
g = {}; exec(src('help.py'), g); HELP = g['HELP']
D.update({
 '%player_n': ['ఆటగాడు {0}: {1}', 'खिलाड़ी {0}: {1}', 'வீரர் {0}: {1}', 'ಆಟಗಾರ {0}: {1}', 'കളിക്കാരൻ {0}: {1}'],
 '%jersey_range': ['జెర్సీ నంబర్ 0 నుండి 999 మధ్య ఉండాలి', 'जर्सी नंबर 0 से 999 के बीच हो', 'ஜெர்சி எண் 0 முதல் 999 வரை இருக்க வேண்டும்', 'ಜರ್ಸಿ ಸಂಖ್ಯೆ 0 ರಿಂದ 999 ಇರಬೇಕು', 'ജേഴ്സി നമ്പർ 0 മുതൽ 999 വരെ ആകണം'],
})
for f in ['d5', 'd6', 'd7']:
    g = {'N': None}; exec(src(f + '.py'), g); D.update(g[f.upper()])
# Results against a rain-revised target reuse the normal result wording
for k in ['%won_runs', '%won_wkts']:
    D[k + '_rev'] = [t + ' (' + r + ')' for t, r in zip(D[k], D['revised target'])]

langs = ['te', 'hi', 'ta', 'kn', 'ml']
X = {l: {} for l in langs}
for k, v in D.items():
    for i, l in enumerate(langs):
        if i < len(v) and v[i]: X[l][k] = v[i]

js = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
out = ('// Stumply — translations and the help guide. GENERATED by tools/i18n/build.py: edit the sources there, not this file.\n'
       '/*HELP_START*/const HELP_DATA=' + js(HELP) + ';/*HELP_END*/\n'
       '/*I18N_X_START*/const I18N_X=' + js(X) + ';/*I18N_X_END*/\n')
open(os.path.join(ROOT, 'js', 'i18n-data.js'), 'w', encoding='utf-8').write(out)
print('js/i18n-data.js written:', {l: len(X[l]) for l in langs})
